package de.gematik.ti.erp.app.pushnotifications.domain

private const val MONTH_DIGITS = 2
private const val FIRST_MONTH = 1
private const val LAST_MONTH = 12

/** Formats the protocol month used for registration and HKDF key derivation as `YYYY-MM`. */
internal fun formatPushNotificationYearMonth(year: Int, monthNumber: Int): String {
    require(monthNumber in FIRST_MONTH..LAST_MONTH) {
        "Month number must be between $FIRST_MONTH and $LAST_MONTH, but was $monthNumber."
    }
    return "$year-${monthNumber.toString().padStart(MONTH_DIGITS, '0')}"
}
